/**
 * Writes `src/theme/palettes.css` and `src/theme/palettes.ts` from the named palettes in
 * `src/theme/themes/`. Each palette file targets `:root` and `.dark`, so importing one retints
 * the whole app for good; palettes.css holds all of them scoped to a choice the page makes at
 * runtime, on `<html>`:
 *
 *   <meta name="ui-palette" content="zinc blue">   or   <html data-palette="zinc blue">
 *
 * A base palette (surfaces) and an accent palette (primary, ring, charts) combine. The module
 * lists them with a few colors each for pickers. Run `pnpm --filter @cossackframework/ui palettes`
 * after changing a palette; a test keeps both files in step.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const THEME = new URL('../src/theme/', import.meta.url);

/** Base palettes retint surfaces; accents retint primary colors. Neutral is theme.css itself. */
export const PALETTES = [
    { id: 'neutral', label: 'Neutral', kind: 'base' },
    { id: 'zinc', label: 'Zinc', kind: 'base' },
    { id: 'gray', label: 'Gray', kind: 'base' },
    { id: 'slate', label: 'Slate', kind: 'base' },
    { id: 'stone', label: 'Stone', kind: 'base' },
    { id: 'neutral', label: 'Neutral', kind: 'accent' },
    { id: 'blue', label: 'Blue', kind: 'accent' },
    { id: 'green', label: 'Green', kind: 'accent' },
    { id: 'red', label: 'Red', kind: 'accent' },
];

const SWATCH = { base: ['sidebar', 'background', 'muted-foreground', 'foreground'], accent: ['primary', 'sidebar-primary', 'chart-1', 'chart-3'] };

/** The `:root` and `.dark` declarations of a palette file (or theme.css). */
function blocks(css) {
    const plain = css.replace(/\/\*[\s\S]*?\*\//g, '');
    const block = selector => {
        const match = new RegExp(`(?:^|\\n)${selector.replace('.', '\\.')}\\s*\\{([^}]*)\\}`).exec(plain);
        if (!match) throw new Error(`no ${selector} block`);
        return [...match[1].matchAll(/--([a-z0-9-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]);
    };
    return { light: block(':root'), dark: block('.dark') };
}

async function source(palette) {
    return blocks(await readFile(new URL(palette.id === 'neutral' ? 'theme.css' : `themes/${palette.id}.css`, THEME), 'utf8'));
}

const declarations = entries => entries.map(([name, value]) => `    --${name}: ${value};`).join('\n');

export async function palettesCss() {
    const parts = [];
    for (const palette of PALETTES) {
        // Neutral is theme.css: it changes nothing; it is listed so pickers can offer it.
        if (palette.id === 'neutral') continue;
        const { light, dark: own } = await source(palette);
        // Scoped, the light block outranks theme.css's .dark, so dark mode sets every token light
        // mode sets: those the file's .dark leaves alone keep theme.css's dark value, as an import would.
        const base = (await source({ id: 'neutral' })).dark;
        const dark = [...own, ...light.filter(([name]) => !own.some(([token]) => token === name)).map(([name]) => {
            const value = base.find(([token]) => token === name);
            if (!value) throw new Error(`${palette.id}: theme.css has no dark value for --${name}`);
            return value;
        })];
        const chosen = `meta[name="ui-palette"][content~="${palette.id}"]`;
        parts.push(`/* ${palette.label} (${palette.kind}) */
:root[data-palette~="${palette.id}"],
:root:has(> head > ${chosen}) {
${declarations(light)}
}

:root.dark[data-palette~="${palette.id}"],
:root.dark:has(> head > ${chosen}) {
${declarations(dark)}
}`);
    }
    return `/*
 * @cossackframework/ui — every named palette, chosen at runtime. Generated by
 * scripts/build-palettes.mjs from src/theme/themes/*.css: do not edit.
 *
 * Import AFTER theme.css, then name a base and an accent palette on <html>:
 *
 *   <meta name="ui-palette" content="zinc blue">   or   <html data-palette="zinc blue">
 */

${parts.join('\n\n')}
`;
}

export async function palettesModule() {
    const entries = [];
    for (const palette of PALETTES) {
        const { light, dark } = await source(palette);
        const value = (entries, name) => entries.find(([token]) => token === name)?.[1];
        const base = await source({ id: 'neutral' });
        const color = (name, mode) => value(mode === 'dark' ? dark : light, name) ?? value(mode === 'dark' ? base.dark : base.light, name);
        entries.push(`    { id: '${palette.id}', label: '${palette.label}', kind: '${palette.kind}', light: [${SWATCH[palette.kind].map(name => `'${color(name, 'light')}'`).join(', ')}], dark: [${SWATCH[palette.kind].map(name => `'${color(name, 'dark')}'`).join(', ')}] },`);
    }
    return `/**
 * The named palettes \`theme/palettes.css\` can switch to (neutral is theme.css), with four colors each (light and
 * dark) for a picker. Generated by scripts/build-palettes.mjs: do not edit.
 */
export interface UiPalette {
    readonly id: string;
    readonly label: string;
    /** \`base\` retints surfaces and text; \`accent\` retints primary colors, rings and charts. */
    readonly kind: 'base' | 'accent';
    readonly light: readonly string[];
    readonly dark: readonly string[];
}

export const UI_PALETTES: readonly UiPalette[] = Object.freeze([
${entries.join('\n')}
]);

/** The \`<meta>\` that names the page's palettes, as \`content="<base> <accent>"\`. */
export const UI_PALETTE_META = 'ui-palette';
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    await writeFile(new URL('palettes.css', THEME), await palettesCss());
    await writeFile(new URL('palettes.ts', THEME), await palettesModule());
    console.log('wrote src/theme/palettes.css and src/theme/palettes.ts');
}
