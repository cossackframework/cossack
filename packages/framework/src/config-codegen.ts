/** Node-only tooling. Factory modules are referenced as types, never evaluated. */
import { existsSync, statSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { mountedPackages, projectPath, servedSpecifier } from './package-mounts.js';
import { pluginLocations } from './plugin-sources.js';

export const CONFIG_TYPES_PATH = '.cossack/config.d.ts';
const HEADER = '// Generated by Cossack configuration tooling. Do not edit.\n';
export const CONFIG_GLOB = ['/src/config/*.ts', '!/src/config/*.d.ts', '!/src/config/*.test.ts', '!/src/config/*.spec.ts'];
/** Plugin configuration, keyed `<plugin>::<file>`: `config('support-desk::tickets.perPage')`. */
export const PLUGIN_CONFIG_GLOB = CONFIG_GLOB.map(pattern => pattern.replace('/src/config/', '/src/plugins/*/config/'));

/** Discover type origins without reading generated output or factory source. */
export function discoverConfigFactories(root: string): string[] {
  return factoryFiles(resolve(root, 'src/config'));
}

export interface ConfigSource {
  /** `config()` key: the file name, or `<plugin>::<file>` for plugin configuration. */
  key: string;
  /** Source path as the project sees it (through `..` or `node_modules` for a mounted package). */
  source: string;
  /** Absolute path of the factory module. */
  file: string;
  /** Package import specifier, for a factory a mounted package exports. */
  specifier?: string;
}

/**
 * Application, package and plugin configuration factories, application first.
 * An application file overrides a mounted package's file of the same name.
 */
export function discoverConfigSources(root: string): ConfigSource[] {
  const entry = (key: string, file: string): ConfigSource => ({ key, source: projectPath(root, file).slice(1), file });
  const sources = discoverConfigFactories(root).map(file => entry(file.slice(0, -3), resolve(root, 'src/config', file)));
  for (const mounted of mountedPackages(root)) for (const path of mounted.config) {
    const key = path.slice('config/'.length, -3);
    const existing = sources.find(source => source.key === key);
    const specifier = servedSpecifier(mounted, path);
    if (!existing && existsSync(join(mounted.root, path))) sources.push({ ...entry(key, join(mounted.root, path)), ...(specifier ? { specifier } : {}) });
  }
  sources.sort((a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0));
  for (const plugin of pluginLocations(root)) {
    const mounted = plugin.package ? mountedPackages(root).find(candidate => candidate.name === plugin.package) : undefined;
    for (const file of factoryFiles(join(plugin.directory, 'config'))) {
      const specifier = mounted ? servedSpecifier(mounted, `plugins/${plugin.name}/config/${file}`) : null;
      sources.push({ ...entry(`${plugin.name}::${file.slice(0, -3)}`, join(plugin.directory, 'config', file)), ...(specifier ? { specifier } : {}) });
    }
  }
  return sources;
}

function factoryFiles(directory: string): string[] {
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.name.endsWith('.ts') && !/\.(?:d|test|spec)\.ts$/.test(entry.name))
    .filter(entry => entry.isFile() || (entry.isSymbolicLink() && statSync(resolve(directory, entry.name)).isFile()))
    .map(entry => entry.name).sort();
}

export function generateConfigTypes(root: string, options: { write?: boolean } = {}) {
  const sources = discoverConfigSources(root);
  const names = discoverConfigFactories(root);
  const source = HEADER + "import '@cossackframework/framework/config';\n" +
    "type FactoryResult<T extends (...args: any[]) => object> = ReturnType<T>;\n" +
    "declare module '@cossackframework/framework/config' {\n  interface CossackGeneratedConfigRegistry {\n" +
    sources.map(entry => `    ${JSON.stringify(entry.key)}: FactoryResult<typeof import(${JSON.stringify(entry.specifier ?? '../' + entry.source)}).default>;`).join('\n') +
    '\n  }\n}\n';
  const file = resolve(root, CONFIG_TYPES_PATH);
  for (const target of [dirname(file), file]) {
    if (lstatSync(target, { throwIfNoEntry: false })?.isSymbolicLink()) {
      throw Object.assign(new Error('Configuration generation cannot replace a symbolic link: ' + target), { code: 'COSSACK_CONFIG_GENERATION_CONFLICT' });
    }
  }
  const previous = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (previous !== null && !previous.startsWith(HEADER)) {
    throw Object.assign(new Error('Configuration generation found an authored .cossack/config.d.ts.'), { code: 'COSSACK_CONFIG_GENERATION_CONFLICT' });
  }
  const changed = source !== previous;
  if (changed && options.write !== false) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, source);
  }
  return { file, source, factories: names, changed };
}
