/** Node-only tooling. Factory modules are referenced as types, never evaluated. */
import { existsSync, statSync, lstatSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

export const CONFIG_TYPES_PATH = '.cossack/config.d.ts';
const HEADER = '// Generated by Cossack configuration tooling. Do not edit.\n';
export const CONFIG_GLOB = ['/src/config/*.ts', '!/src/config/*.d.ts', '!/src/config/*.test.ts', '!/src/config/*.spec.ts'];

/** Discover type origins without reading generated output or factory source. */
export function discoverConfigFactories(root: string): string[] {
  const directory = resolve(root, 'src/config');
  if (!existsSync(directory)) return [];
  return readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.name.endsWith('.ts') && !/\.(?:d|test|spec)\.ts$/.test(entry.name))
    .filter(entry => entry.isFile() || (entry.isSymbolicLink() && statSync(resolve(directory, entry.name)).isFile()))
    .map(entry => entry.name).sort();
}

export function generateConfigTypes(root: string, options: { write?: boolean } = {}) {
  const names = discoverConfigFactories(root);
  const source = HEADER + "import '@cossackframework/framework/config';\n" +
    "type FactoryResult<T extends (...args: any[]) => object> = ReturnType<T>;\n" +
    "declare module '@cossackframework/framework/config' {\n  interface CossackGeneratedConfigRegistry {\n" +
    names.map(name => `    ${JSON.stringify(name.slice(0, -3))}: FactoryResult<typeof import(${JSON.stringify('../src/config/' + name)}).default>;`).join('\n') +
    '\n  }\n}\n';
  const file = resolve(root, CONFIG_TYPES_PATH);
  for (const target of [dirname(file), file]) {
    if (lstatSync(target, { throwIfNoEntry: false })?.isSymbolicLink()) {
      throw Object.assign(new Error('Configuration generation cannot replace a symbolic link: ' + target), { code: 'COSSACK_CONFIG_GENERATION_CONFLICT' });
    }
  }
  const previous = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (previous !== null && !previous.startsWith(HEADER)) {
    throw Object.assign(new Error('Configuration generation found an authored .cossack/config.d.ts.'), { code: 'COSSACK_CONFIG_GENERATION_CONFLICT' });
  }
  const changed = source !== previous;
  if (changed && options.write !== false) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, source);
  }
  return { file, source, factories: names, changed };
}
