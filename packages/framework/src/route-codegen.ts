/** Node-only compiler output. The core URL helper remains portable. */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { parseSync } from 'vite';
import { buildRoutesManifest, classifyRoute, computeRouteIds, filePathToHttpRoute, type RoutesManifest } from './route-ids.js';
import { scanPageSources } from './plugin-sources.js';
import { isHttpHandlerProgram } from './page-inspection.js';

export const ROUTES_MODULE_ID = 'virtual:cossack-routes';
export const ROUTES_SOURCE_PATH = '.cossack/routes.ts';
const GENERATED_HEADER = '// Generated by Cossack. Run cossack routes --generate to update.\n';
const TEST_DIRECTORIES = new Set(['__tests__', '__fixtures__', 'fixtures']);
/** Keep virtual glob exclusions and the filesystem walk on the same contract. */
export const ROUTE_GLOB_EXCLUDES = [
  '!/src/pages/**/*.d.ts', '!/src/pages/**/*.test.*', '!/src/pages/**/*.spec.*',
  ...[...TEST_DIRECTORIES].map(directory => `!/src/pages/**/${directory}/**`),
];

export function scanPagesDir(
  pagesDir: string,
  includeMarkdown = false,
): { pageKeys: string[]; layoutKeys: string[]; markdownKeys: string[] } {
  const pageKeys: string[] = [];
  const layoutKeys: string[] = [];
  const markdownKeys: string[] = [];
  if (!existsSync(pagesDir)) return { pageKeys, layoutKeys, markdownKeys };

  const walk = (dir: string) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const fullPath = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (TEST_DIRECTORIES.has(entry.name)) continue;
        walk(fullPath);
      } else if (entry.isFile()) {
        if (/\.(?:test|spec)\.[^.]+$/.test(entry.name) || entry.name.endsWith('.d.ts')) {
          continue;
        }
        const rel = relative(pagesDir, fullPath).split(sep).join('/');
        const key = `/src/pages/${rel}`;
        if (entry.name === 'layout.ts') {
          layoutKeys.push(key);
        } else if (entry.name === 'loading.ts') {
          // Excluded — matches the glob's `!/src/pages/**/loading.ts`.
        } else if (entry.name.endsWith('.mdx') || entry.name.endsWith('.md')) {
          markdownKeys.push(key);
          if (includeMarkdown) pageKeys.push(key);
        } else if (entry.name.endsWith('.ts')) {
          pageKeys.push(key);
        }
      }
    }
  };

  walk(pagesDir);
  return { pageKeys: pageKeys.sort(), layoutKeys: layoutKeys.sort(), markdownKeys: markdownKeys.sort() };
}

/** Parse results by source file; a page is parsed again only when its size or mtime changes. */
const handlerSyntax = new Map<string, { size: number; mtimeMs: number; handler: boolean }>();

/**
 * Route keys of the functional HTTP handler modules outside `/api`: TypeScript page
 * files whose exports are a default function, `defineApi()` or `GET`/`POST`… handlers
 * rather than a component. The same Oxc parse that the client security plugin uses
 * decides, so the manifest, the generated API types and the browser stubs agree, and
 * nothing executes. Modules under `/api` are endpoints by path and are not parsed;
 * Markdown pages are never handlers.
 */
export function discoverHttpHandlers(projectRoot: string, pageKeys: readonly string[], sources: Record<string, string> = {}): string[] {
  const handlers: string[] = [];
  for (const key of pageKeys) {
    if (!key.endsWith('.ts') || classifyRoute(filePathToHttpRoute(key)) !== 'page') continue;
    const file = resolve(projectRoot, '.' + (sources[key] ?? key));
    const { size, mtimeMs } = statSync(file);
    const cached = handlerSyntax.get(file);
    const handler = cached && cached.size === size && cached.mtimeMs === mtimeMs ? cached.handler : isHttpHandlerSource(readFileSync(file, 'utf8'));
    handlerSyntax.set(file, { size, mtimeMs, handler });
    if (handler) handlers.push(key);
  }
  return handlers;
}

function isHttpHandlerSource(code: string): boolean {
  try {
    const result = parseSync('page.ts', code);
    return !result.errors?.length && isHttpHandlerProgram(result.program);
  } catch { return false; }
}

/**
 * Same discovered files and collision resolution as virtual:cossack-pages,
 * including plugin pages under `src/plugins/<name>/pages`. Functional handlers
 * outside `/api` are endpoints by their syntax ({@link discoverHttpHandlers}).
 */
export function discoverRoutes(projectRoot: string, includeMarkdown = false): RoutesManifest {
  const { pageKeys, layoutKeys, sources } = scanPageSources(projectRoot, includeMarkdown);
  const handlers = discoverHttpHandlers(projectRoot, pageKeys, sources);
  const manifest = buildRoutesManifest(pageKeys, layoutKeys, computeRouteIds(pageKeys, layoutKeys), { handlers });
  const pluginSources = Object.fromEntries(Object.entries(sources).filter(([key, source]) => key !== source));
  return Object.keys(pluginSources).length ? { ...manifest, sources: pluginSources } : manifest;
}

/** Runtime paths plus type-only native exports. No application runtime imports enter the client graph. */
export function renderRouteSource(manifest: RoutesManifest): string {
  const patterns = Object.fromEntries(manifest.routes.filter(route => route.addressable).map(route => [route.name, route.pattern]));
  const apiModules = manifest.routes.filter(route => route.kind === 'api' && route.addressable)
    .map(route => `  ${JSON.stringify(route.name)}: typeof import(${JSON.stringify('..' + (manifest.sources?.[route.filePath] ?? route.filePath))});`).join('\n');
  return GENERATED_HEADER + "import { createRouteBuilder } from '@cossackframework/core/routes';\n" +
    `export const routePatterns = ${JSON.stringify(patterns, null, 2)} as const;\n` +
    'export const routes = createRouteBuilder(routePatterns);\n' +
    "import type { ApiMethods, ApiRawInput, ApiOutput } from '@cossackframework/framework/api';\n" +
    `type ApiModules = {\n${apiModules}\n};\n` +
    'export type ApiRoutes = { [N in keyof ApiModules as keyof ApiMethods<ApiModules[N]> extends never ? never : N]: ApiMethods<ApiModules[N]> };\n' +
    'export type ApiRequest<N extends keyof ApiRoutes, M extends keyof ApiRoutes[N]> = ApiRawInput<ApiRoutes[N][M]>;\n' +
    'export type ApiResponse<N extends keyof ApiRoutes, M extends keyof ApiRoutes[N]> = ApiOutput<ApiRoutes[N][M]>;\n';
}

export function generateRoutes(projectRoot: string, options: { includeMarkdown?: boolean; write?: boolean } = {}): {
  manifest: RoutesManifest; source: string; file: string; changed: boolean;
} {
  const manifest = discoverRoutes(projectRoot, options.includeMarkdown ?? false);
  const source = renderRouteSource(manifest);
  const file = resolve(projectRoot, ROUTES_SOURCE_PATH);
  const previous = existsSync(file) ? readFileSync(file, 'utf8') : null;
  if (previous !== null && !previous.startsWith(GENERATED_HEADER)) {
    throw Object.assign(new Error('Route generation found an authored .cossack/routes.ts. Move that file before generating routes.'),
      { code: 'COSSACK_ROUTE_GENERATION_CONFLICT' });
  }
  const changed = previous !== source;
  if (options.write !== false && changed) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, source);
  }
  return { manifest, source, file, changed };
}
