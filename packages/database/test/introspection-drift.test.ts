@Entity({ tableName: "accounts" })
class DriftAccount extends BaseEntity {
  @PrimaryGeneratedColumn() declare id: number;
  @Column({ type: "varchar", unique: true }) declare email: string;
  @Index("idx_accounts_handle", { unique: true })
  @Column({ type: "varchar", length: 64 }) declare handle: string;
  @Column({ type: "boolean", default: false }) declare active: boolean;
  @Column({ type: "enum", enum: ["draft", "published"], default: "draft" }) declare status: "draft" | "published";
  @Column({ type: "decimal", precision: 12, scale: 2, default: 0 }) declare total: string;
  @CreateDateColumn({ default: "CURRENT_TIMESTAMP" }) declare createdAt: Date;
}

@Entity({ tableName: "tickets" })
class DriftTicket extends BaseEntity {
  // Application-assigned integer key: a rowid alias, but not generated by the model.
  @PrimaryColumn({ type: "integer" }) declare id: number;
  @Column({ type: "text", nullable: true }) declare note: string | null;
  @ManyToMany(() => DriftLabel) @JoinTable({ name: "ticket_labels" }) declare labels: DriftLabel[];
}

@Entity({ tableName: "labels" })
class DriftLabel extends BaseEntity {
  @PrimaryColumn({ type: "integer" }) declare id: number;
}

// The generated sessions table: SQLite cannot ADD COLUMN ... UNIQUE, so the
// migration adds the column and a separate unique index.
@Entity({ tableName: "tokens" })
class DriftToken extends BaseEntity {
  @PrimaryColumn({ type: "varchar" }) declare id: string;
  @Index("tokens_public_id_unique", { unique: true })
  @Column({ type: "varchar", name: "public_id", length: 36, nullable: true, unique: true }) declare publicId: string | null;
}

describe("SQLite drift", () => {
  it("reports no drift for tables created from the model's own DDL", async () => {
    const orm = createORM({ adapter: await nodeSQLite(), entities: [DriftAccount, DriftTicket, DriftLabel] });
    try {
      await orm.run(async () => {
        for (const entity of orm.schema().entities) await new SchemaBuilder().createTable(entity).execute(orm);
        const physical = await orm.introspect();
        const accounts = physical.entities.find((entity) => entity.tableName === "accounts")!;
        expect(accounts.columns.find((column) => column.columnName === "handle")?.unique).toBe(false);
        expect(accounts.columns.find((column) => column.columnName === "email")?.unique).toBe(true);
        expect(accounts.columns.find((column) => column.columnName === "status")?.enumValues).toEqual(["draft", "published"]);
        expect(accounts.indexes).toEqual([{ name: "idx_accounts_handle", columns: ["handle"], unique: true }]);
        expect(diffSchemas(physical, orm.schema()).operations).toEqual([]);
      });
    } finally {
      await orm.close();
    }
  });

  it("treats a single-column unique index as the column's UNIQUE rule", async () => {
    const orm = createORM({ adapter: await nodeSQLite(), entities: [DriftToken] });
    try {
      await orm.run(async () => {
        await orm.sql`CREATE TABLE tokens (id VARCHAR(255) NOT NULL PRIMARY KEY)`;
        await orm.sql`ALTER TABLE tokens ADD COLUMN public_id VARCHAR(36)`;
        await orm.sql`CREATE UNIQUE INDEX tokens_public_id_unique ON tokens (public_id)`;
        expect(diffSchemas(await orm.introspect(), orm.schema()).operations).toEqual([]);
      });
    } finally {
      await orm.close();
    }
  });
});

const postgresColumn = (column_name: string, data_type: string, extra: Record<string, unknown> = {}) => ({
  table_name: "accounts", column_name, data_type, not_null: true, column_default: null,
  identity_kind: "", generated_kind: "", is_primary: false, is_unique: false, ...extra,
});

describe("PostgreSQL drift", () => {
  for (const definition of [
    "CHECK (status::text = ANY (ARRAY['draft'::character varying, 'published'::character varying]::text[]))",
    "CHECK (((status)::text = ANY ((ARRAY['draft'::character varying, 'published'::character varying])::text[])))",
  ]) {
    it(`maps the ORM's enum CHECK back to enum values and normalizes now() (${definition.slice(0, 12)})`, async () => {
      const physical = await introspectPostgres(async (text) => {
        if (text.includes("FROM pg_catalog.pg_attribute")) {
          return { rows: [
            postgresColumn("id", "integer", { identity_kind: "d", is_primary: true }),
            postgresColumn("email", "character varying(255)", { is_unique: true }),
            postgresColumn("handle", "character varying(64)"),
            postgresColumn("active", "boolean", { column_default: "false" }),
            postgresColumn("status", "character varying", { column_default: "'draft'::character varying" }),
            postgresColumn("total", "numeric(12,2)", { column_default: "0" }),
            postgresColumn("created_at", "timestamp with time zone", { column_default: "CURRENT_TIMESTAMP" }),
          ] } as never;
        }
        if (text.includes("FROM pg_catalog.pg_index")) {
          return { rows: [{
            table_name: "accounts", index_name: "idx_accounts_handle", is_unique: true, is_primary: false,
            access_method: "btree", constraint_type: null, is_expression: false, is_partial: false,
            definition: "CREATE UNIQUE INDEX idx_accounts_handle ON public.accounts USING btree (handle)",
            index_columns: ["handle"],
          }] } as never;
        }
        return { rows: [{ table_name: "accounts", constraint_name: "accounts_status_check", constraint_type: "c", definition }] } as never;
      });
      expect(physical.entities[0]?.columns.find((column) => column.columnName === "status"))
        .toMatchObject({ logicalType: "enum", enumValues: ["draft", "published"], default: "draft" });
      const orm = createORM({ adapter: { driver: new MemoryDriver("postgres") }, entities: [DriftAccount] });
      expect(diffSchemas(physical, orm.schema()).operations).toEqual([]);
      await orm.close();
    });
  }

  it("still refuses checks that are not the ORM's enum shape", async () => {
    await expect(introspectPostgres(async (text) => {
      if (text.includes("FROM pg_catalog.pg_attribute")) return { rows: [postgresColumn("status", "character varying")] } as never;
      if (text.includes("FROM pg_catalog.pg_index")) return { rows: [] } as never;
      return { rows: [{
        table_name: "accounts", constraint_name: "accounts_status_check", constraint_type: "c",
        definition: "CHECK (status::text = ANY (ARRAY['a'::character varying]::text[]) OR status IS NULL)",
      }] } as never;
    })).rejects.toThrow(/accounts_status_check/);
  });
});

@Entity({ tableName: "posts" })
class DriftPost extends BaseEntity {
  @PrimaryGeneratedColumn() declare id: number;
  @Column({ type: "varchar" }) declare title: string;
  @ManyToOne(() => DriftAccount) declare author: DriftAccount | null;
}

describe("MySQL introspection", () => {
  const mysqlColumn = (table_name: string, column_name: string, column_type: string, extra: Record<string, unknown> = {}) => ({
    table_name, column_name, column_type, is_nullable: "NO", column_default: null, column_key: "", extra: "", ...extra,
  });
  const index = (table_name: string, index_name: string, column_name: string, non_unique: number) => ({
    table_name, index_name, non_unique, seq_in_index: 1, column_name, sub_part: null, index_type: "BTREE",
  });

  // Tables created before DATETIME(3) keep a bare DATETIME; neither form drifts from the model.
  it.each([
    ["datetime", "CURRENT_TIMESTAMP"],
    ["datetime(3)", "CURRENT_TIMESTAMP(3)"],
  ])("reads column types, indexes, defaults and enum checks without drift (%s)", async (createdType, createdDefault) => {
    const queries: string[] = [];
    const driver = new MemoryDriver("mysql", (query) => {
      queries.push(query.text);
      if (query.text.includes("information_schema.columns")) {
        return { rows: [
          mysqlColumn("accounts", "id", "int", { column_key: "PRI", extra: "auto_increment" }),
          mysqlColumn("accounts", "email", "varchar(255)", { column_key: "UNI" }),
          mysqlColumn("accounts", "handle", "varchar(64)", { column_key: "UNI" }),
          mysqlColumn("accounts", "active", "tinyint(1)", { column_default: "0" }),
          mysqlColumn("accounts", "status", "varchar(255)", { column_default: "draft" }),
          mysqlColumn("accounts", "total", "decimal(12,2)", { column_default: "0.00" }),
          mysqlColumn("accounts", "created_at", createdType, { column_default: createdDefault, extra: "DEFAULT_GENERATED" }),
          mysqlColumn("posts", "id", "int", { column_key: "PRI", extra: "auto_increment" }),
          mysqlColumn("posts", "title", "varchar(255)"),
          mysqlColumn("posts", "author_id", "int", { is_nullable: "YES", column_key: "MUL" }),
        ] };
      }
      if (query.text.includes("information_schema.statistics")) {
        return { rows: [
          index("accounts", "PRIMARY", "id", 0),
          index("accounts", "email", "email", 0),
          index("accounts", "idx_accounts_handle", "handle", 0),
          index("posts", "PRIMARY", "id", 0),
          index("posts", "author_id", "author_id", 1),
        ] };
      }
      if (query.text.includes("information_schema.key_column_usage")) {
        return { rows: [{ table_name: "posts", constraint_name: "posts_ibfk_1", column_name: "author_id" }] };
      }
      if (query.text.includes("information_schema.check_constraints")) {
        return { rows: [{
          table_name: "accounts", constraint_name: "accounts_chk_1",
          check_clause: "(`status` in (_utf8mb4\\'draft\\',_utf8mb4\\'published\\'))",
        }] };
      }
      return { rows: [] };
    });
    const orm = createORM({ adapter: { driver }, entities: [DriftAccount, DriftPost] });
    const physical = await introspectMySQL((text, parameters = []) => driver.execute({ text, parameters }, "select"));
    expect(queries.every((text) => text.includes("<> '_cossack_migrations'") || text.includes("key_column_usage"))).toBe(true);
    const accounts = physical.entities.find((entity) => entity.tableName === "accounts")!;
    expect(accounts.columns.map(({ columnName, logicalType, length, unique, default: value }) =>
      ({ columnName, logicalType, length, unique, default: value }))).toEqual([
      { columnName: "id", logicalType: "integer", length: undefined, unique: false, default: undefined },
      { columnName: "email", logicalType: "varchar", length: 255, unique: true, default: undefined },
      { columnName: "handle", logicalType: "varchar", length: 64, unique: false, default: undefined },
      { columnName: "active", logicalType: "boolean", length: undefined, unique: false, default: "0" },
      { columnName: "status", logicalType: "enum", length: undefined, unique: false, default: "draft" },
      { columnName: "total", logicalType: "decimal", length: undefined, unique: false, default: 0 },
      { columnName: "created_at", logicalType: "datetime", length: undefined, unique: false, default: createdDefault },
    ]);
    expect(accounts.indexes).toEqual([{ name: "idx_accounts_handle", columns: ["handle"], unique: true }]);
    expect(physical.entities.find((entity) => entity.tableName === "posts")?.indexes).toEqual([]);
    expect(diffSchemas(physical, orm.schema()).operations).toEqual([]);
    await orm.close();
  });

  it("emits a sized VARCHAR for enum columns", () => {
    const statement = createTableDDL(createORM({ adapter: { driver: new MemoryDriver("mysql") }, entities: [DriftAccount] })
      .schema().entities[0]!, mysqlDialect)[0]!;
    expect(statement).toContain("`status` varchar(255) NOT NULL DEFAULT 'draft' CHECK (`status` IN ('draft', 'published'))");
  });

  it("keeps milliseconds with DATETIME(3) and a matching CURRENT_TIMESTAMP(3) default", () => {
    const statement = createTableDDL(createORM({ adapter: { driver: new MemoryDriver("mysql") }, entities: [DriftAccount] })
      .schema().entities[0]!, mysqlDialect)[0]!;
    // MySQL rejects `DATETIME(3) DEFAULT CURRENT_TIMESTAMP` as an invalid default.
    expect(statement).toContain("`created_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)");
  });
});
