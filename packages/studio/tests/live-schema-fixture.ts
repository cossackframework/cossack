export function fixtureSchema(dialect: LiveDialect): string[] {
  return dialect === 'postgres' ? POSTGRES_SCHEMA : MYSQL_SCHEMA;
}

export function dropFixtureSchema(dialect: LiveDialect): string[] {
  const quote = (name: string) => dialect === 'postgres' ? `"${name}"` : `\`${name}\``;
  const cascade = dialect === 'postgres' ? ' CASCADE' : '';
  return [
    ...VIEWS.map((name) => `DROP VIEW IF EXISTS ${quote(name)}${cascade}`),
    ...TABLES.map((name) => `DROP TABLE IF EXISTS ${quote(name)}${cascade}`),
    ...(dialect === 'postgres' ? ['DROP TYPE IF EXISTS sl_order_status'] : []),
  ];
}

/** Extra tables that must not change the number of introspection queries. */
export function extraTables(dialect: LiveDialect): string[] {
  const reference = dialect === 'postgres'
    ? 'account_id integer REFERENCES sl_accounts (id)'
    : 'account_id int NULL, FOREIGN KEY (account_id) REFERENCES sl_accounts (id)';
  return [1, 2, 3].map((index) =>
    `CREATE TABLE sl_extra_${index} (id integer PRIMARY KEY, label varchar(20) UNIQUE, ${reference})`);
}

/**
 * The fixture objects as stable JSON: the database name and MySQL view
 * definers depend on the connection, not on Studio.
 */
export function fixtureSnapshot(objects: StudioObject[], databaseName: string): string {
  const fixture = objects.filter((object) =>
    object.name.startsWith(FIXTURE_PREFIX) && !object.name.startsWith(`${FIXTURE_PREFIX}extra_`));
  return `${JSON.stringify(fixture, null, 2)
    .replaceAll(`\`${databaseName}\`.`, '`<database>`.')
    .replace(/DEFINER=`[^`]*`@`[^`]*`/g, 'DEFINER=<definer>')}\n`;
}
